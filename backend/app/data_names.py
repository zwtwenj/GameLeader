"""随机角色名池：姓 + 名 组合（组合空间 ~1600，角色名 2~3 字）。

plan.md 提到以后做"角色名的表"——到时把 pick_random_name 换成查表实现即可，
调用方无感。名字不能与团队现有成员重复由调用方传 exclude 保证。
"""

import random

SURNAMES = [
    "李", "王", "张", "刘", "陈", "杨", "赵", "黄", "周", "吴",
    "徐", "孙", "马", "朱", "胡", "郭", "何", "林", "罗", "高",
    "郑", "梁", "谢", "宋", "唐", "韩", "冯", "于", "董", "程",
    "曹", "袁", "邓", "许", "沈", "曾", "彭", "吕", "苏", "卢",
]

GIVEN_NAMES = [
    "剑心", "青枫", "云涛", "月寒", "孤鸿", "长风", "疏影", "听雨",
    "半夏", "沧澜", "白鹭", "秋水", "凌霜", "惊鸿", "醉墨", "归鸿",
    "清欢", "无涯", "星眠", "雪见", "流云", "竹隐", "慕辞", "江晚",
    "山月", "未央", "千帆", "平生", "夜白", "望舒", "既明", "沐风",
    "扶摇", "南絮", "北辰", "知非", "行舟", "照野", "停云", "亦寒",
]


def pick_random_name(exclude: set[str], attempts: int = 100) -> str:
    """随机取一个不在 exclude 里的名字（组合空间远大于排除集，几乎必中）。"""
    for _ in range(attempts):
        name = random.choice(SURNAMES) + random.choice(GIVEN_NAMES)
        if name not in exclude:
            return name
    raise ValueError(f"随机名字池耗尽（排除集过大：{len(exclude)}）")
